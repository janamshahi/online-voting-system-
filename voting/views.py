# =====================================================
# HOME PAGE
# =====================================================
def home(request):
    elections = Election.objects.filter(
        is_published=True
    ).order_by("-opens_at")

    return render(
        request,
        "voting/home.html",
        {
            "elections": elections,
            "now": timezone.now(),
        },
    )


# =====================================================
# STUDENT REGISTRATION
# Student ID is generated by VoterProfile.save()
# =====================================================
def register(request):
    if request.user.is_authenticated:
        return redirect("home")

    if request.method == "POST":
        form = UserCreationForm(request.POST)

        if form.is_valid():
            try:
                with transaction.atomic():
                    user = form.save()

                    profile = VoterProfile.objects.create(
                        user=user,
                        is_eligible=False,
                    )

                messages.success(
                    request,
                    (
                        "Account created successfully! "
                        f"Your Student ID is {profile.student_id}. "
                        "An administrator must approve your voter "
                        "eligibility before you can vote."
                    ),
                )

                return redirect("login")

            except IntegrityError:
                form.add_error(
                    None,
                    "Your account could not be created. "
                    "Please try again with a different username.",
                )

    else:
        form = UserCreationForm()

    return render(
        request,
        "registration/register.html",
        {"form": form},
    )


# =====================================================
# FORGOT PASSWORD
# Username-based reset without email
# =====================================================
def forgot_password(request):
    if request.user.is_authenticated:
        return redirect("home")

    if request.method == "POST":
        username = request.POST.get(
            "username", ""
        ).strip()

        new_password = request.POST.get(
            "new_password", ""
        )

        confirm_password = request.POST.get(
            "confirm_password", ""
        )

        # Check required fields.
        if not username or not new_password or not confirm_password:
            messages.error(
                request,
                "Please complete all fields.",
            )

        elif new_password != confirm_password:
            messages.error(
                request,
                "The new passwords do not match.",
            )

        else:
            User = get_user_model()

            user = User.objects.filter(
                username__iexact=username,
                is_active=True,
            ).first()

            if user is None:
                messages.error(
                    request,
                    "No active account was found with that username.",
                )

            else:
                try:
                    # Apply Django's configured password validators.
                    validate_password(
                        new_password,
                        user=user,
                    )

                    # Store the password securely as a hash.
                    user.set_password(new_password)

                    user.save(
                        update_fields=["password"]
                    )

                    messages.success(
                        request,
                        (
                            "Your password has been reset successfully. "
                            "You can now log in with your new password."
                        ),
                    )

                    return redirect("login")

                except ValidationError as error:
                    for message in error.messages:
                        messages.error(
                            request,
                            message,
                        )

    return render(
        request,
        "registration/forgot_password.html",
    )


