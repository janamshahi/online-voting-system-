# ELECTION DETAILS
# =====================================================
@login_required
def election_detail(request, election_id):
    election = get_object_or_404(
        Election,
        pk=election_id,
        is_published=True,
    )

    profile = getattr(
        request.user,
        "voter_profile",
        None,
    )

    has_voted = Participation.objects.filter(
        election=election,
        voter=request.user,
    ).exists()

    candidates = election.candidates.filter(
        is_active=True,
    ).order_by("full_name")

    return render(
        request,
        "voting/election_detail.html",
        {
            "election": election,
            "candidates": candidates,
            "profile": profile,
            "has_voted": has_voted,
            "is_open": election.is_open,
        },
    )


# =====================================================
# CAST VOTE
# =====================================================
@login_required
def cast_vote(request, election_id):
    if request.method != "POST":
        return redirect(
            "election_detail",
            election_id=election_id,
        )

    candidate_id = request.POST.get("candidate")

    try:
        with transaction.atomic():
            election = get_object_or_404(
                Election.objects.select_for_update(),
                pk=election_id,
                is_published=True,
            )

            profile = VoterProfile.objects.filter(
                user=request.user,
            ).first()

            if profile is None or not profile.is_eligible:
                return HttpResponseForbidden(
                    "Your voter account is not approved."
                )

            if not election.is_open:
                messages.error(
                    request,
                    "This election is not currently open.",
                )

                return redirect(
                    "election_detail",
                    election_id=election.id,
                )

            candidate = get_object_or_404(
                Candidate,
                pk=candidate_id,
                election=election,
                is_active=True,
            )

            # The database constraint prevents duplicate participation.
            Participation.objects.create(
                election=election,
                voter=request.user,
            )

            # Record the selected candidate's ballot.
            Ballot.objects.create(
                election=election,
                candidate=candidate,
            )

    except IntegrityError:
        messages.error(
            request,
            (
                "You have already voted in this election, "
                "or your vote could not be recorded."
            ),
        )

        return redirect(
            "election_detail",
            election_id=election_id,
        )

    messages.success(
        request,
        "Your vote has been submitted successfully.",
    )

    return redirect(
        "election_detail",
        election_id=election_id,
    )


