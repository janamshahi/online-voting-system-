# ELECTION RESULTS AND WINNERS
# =====================================================
@login_required
def results(request, election_id):
    election = get_object_or_404(
        Election,
        pk=election_id,
        is_published=True,
    )

    # Only staff can view unpublished results.
    if (
        not election.results_published
        and not request.user.is_staff
    ):
        return HttpResponseForbidden(
            "Results have not been published yet."
        )

    candidates = (
        Candidate.objects.filter(
            election=election,
        )
        .annotate(
            vote_count=Count(
                "ballots",
                filter=Q(
                    ballots__election=election
                ),
            )
        )
        .order_by(
            "-vote_count",
            "full_name",
        )
    )

    total_votes = Ballot.objects.filter(
        election=election,
    ).count()

    rows = [
        {
            "candidate": candidate,
            "votes": candidate.vote_count,
        }
        for candidate in candidates
    ]

    # Find the highest vote count.
    highest_votes = (
        rows[0]["votes"]
        if rows
        else 0
    )

    # Do not declare a winner if no ballots were cast.
    winners = (
        [
            row
            for row in rows
            if row["votes"] == highest_votes
        ]
        if total_votes > 0
        else []
    )

    winner_ids = {
        row["candidate"].id
        for row in winners
    }

    for row in rows:
        row["is_winner"] = (
            row["candidate"].id in winner_ids
        )

    return render(
        request,
        "voting/results.html",
        {
            "election": election,
            "rows": rows,
            "total_votes": total_votes,
            "winners": winners,
            "has_winner": bool(winners),
            "is_tie": len(winners) > 1,
        },
    )
